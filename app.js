const galleryBatchSize = 12;
let activeFilter = gallery?.dataset.galleryDefault || "all";
let visibleGalleryCount = galleryBatchSize;
let currentGalleryItems = [];
let currentLightboxIndex = 0;

function makeTitle(file, category, index) {
  const base = file
    .split("/")
    .pop()
    .replace(/\.(png|jpg|jpeg|webp)$/i, "")
    .replace(/^\d+-/, "")
    .replace(new RegExp(`^${category}-`), "")
    .replace(/\b(?:img|dsc)\s*\d+[a-z]*\b/gi, "")
    .replace(/\b(img|dsc|hr|sw|nw|se|blnd)\b/gi, "")
    .replace(/\b\d{4,}\b/g, "")
    .replace(/-/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  if (!base || /^\d+$/.test(base)) {
    return `${labels[category]} project ${String(index).padStart(2, "0")}`;
  }

  return base
    .split(" ")
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}

function renderGallery(filter = "all") {
  if (!gallery || !galleryCount) return;

  const items =
    filter === "all" ? galleryItems : galleryItems.filter((item) => item.category === filter);
  currentGalleryItems = items;
  const visibleItems = items.slice(0, visibleGalleryCount);

  gallery.replaceChildren(
    ...visibleItems.map((item, index) => {
      const button = document.createElement("button");
      button.className = "gallery-item";
      button.type = "button";
      button.dataset.category = item.category;
      button.dataset.src = item.file;
      button.dataset.caption = `${labels[item.category]}: ${item.title}`;
      button.dataset.index = String(index);
      button.innerHTML = `
        <img src="${item.file}" alt="${item.title}" loading="lazy">
        <span>${labels[item.category]}</span>
        <strong>${item.title}</strong>
      `;
      return button;
    })
  );

  galleryCount.textContent = `Showing ${visibleItems.length} of ${items.length} ${items.length === 1 ? "image" : "images"}`;

  if (galleryLoadButton) {
    const hasMore = visibleItems.length < items.length;
    galleryLoadButton.closest(".gallery-actions").hidden = !hasMore;
    galleryLoadButton.hidden = !hasMore;
    galleryLoadButton.textContent = hasMore
      ? `Show ${Math.min(galleryBatchSize, items.length - visibleItems.length)} more`
      : "All images shown";
  }

  enhancePointerEffects(gallery);
}

function setActiveFilter(filter) {
  activeFilter = filter;
  visibleGalleryCount = galleryBatchSize;
  filterButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.filter === filter);
  });
  renderGallery(filter);
}

function syncFilterCounts() {
  const counts = {
    all: galleryItems.length,
    kitchens: galleryFiles.kitchens.length,
    bathrooms: galleryFiles.bathrooms.length,
    showroom: galleryFiles.showroom.length
  };

  filterCountBadges.forEach((badge) => {
    badge.textContent = String(counts[badge.dataset.filterCount] || 0);
  });
}

function openLightbox(index) {
  if (!lightbox || !lightboxImage || !lightboxCaption || !closeLightboxButton) return;

  currentLightboxIndex = index;
  const item = currentGalleryItems[currentLightboxIndex];
  if (!item) return;

  const caption = `${labels[item.category]}: ${item.title}`;
  lightboxImage.src = item.file;
  lightboxImage.alt = caption;
  lightboxCaption.textContent = caption;

  if (lightboxPosition) {
    lightboxPosition.textContent = `${currentLightboxIndex + 1} of ${currentGalleryItems.length}`;
  }

  lightbox.classList.add("is-open");
  lightbox.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";
  closeLightboxButton.focus();
}

function closeLightbox() {
  if (!lightbox || !lightboxImage) return;

  lightbox.classList.remove("is-open");
  lightbox.setAttribute("aria-hidden", "true");
  lightboxImage.src = "";
  document.body.style.overflow = "";
}

function moveLightbox(direction) {
  if (!currentGalleryItems.length) return;

  const nextIndex =
    (currentLightboxIndex + direction + currentGalleryItems.length) % currentGalleryItems.length;
  openLightbox(nextIndex);
}

function enhancePointerEffects(root = document) {
  const selector = [
    ".button",
    ".tab",
    ".brand",
    ".site-nav a",
    ".nav-toggle",
    ".hero-proof span",
    ".gallery-item",
    ".person",
    ".steps > div",
    ".review-grid figure",
    ".process-image",
    ".feature-grid img",
    ".award-strip",
    ".proof-mark",
    ".seo-card",
    ".content-card",
    ".faq-grid article",
    ".related-links a",
    ".footer-column a",
    ".footer-bottom a",
    ".footer-logo",
    ".lead-form input",
    ".lead-form select",
    ".lead-form textarea",
    ".lightbox-close",
    ".lightbox-nav"
  ].join(",");

  const finePointer = window.matchMedia("(hover: hover) and (pointer: fine)").matches;

  root.querySelectorAll(selector).forEach((element) => {
    if (element.dataset.pointerEnhanced === "true") return;
    element.dataset.pointerEnhanced = "true";

    element.addEventListener("pointerenter", () => {
      element.classList.add("is-pointer-active");
    });

    element.addEventListener("pointermove", (event) => {
      const rect = element.getBoundingClientRect();
      const x = ((event.clientX - rect.left) / rect.width) * 100;
      const y = ((event.clientY - rect.top) / rect.height) * 100;
      element.style.setProperty("--pointer-x", `${Math.max(0, Math.min(100, x))}%`);
      element.style.setProperty("--pointer-y", `${Math.max(0, Math.min(100, y))}%`);

      if (finePointer) {
        const tiltX = ((50 - y) / 50) * 3.2;
        const tiltY = ((x - 50) / 50) * 3.2;
        element.style.setProperty("--tilt-x", `${tiltX.toFixed(2)}deg`);
        element.style.setProperty("--tilt-y", `${tiltY.toFixed(2)}deg`);
      }
    });

    element.addEventListener("pointerleave", () => {
      element.classList.remove("is-pointer-active");
      element.style.removeProperty("--pointer-x");
      element.style.removeProperty("--pointer-y");
      element.style.removeProperty("--tilt-x");
      element.style.removeProperty("--tilt-y");
    });
  });
}

function syncHeader() {
  if (!header) return;

  header.classList.toggle("is-scrolled", window.scrollY > 20);
}

function settleInitialHash() {
  if (!window.location.hash) return;

  const target = document.querySelector(window.location.hash);
  if (!target) return;

  window.requestAnimationFrame(() => {
    const offset = (header?.offsetHeight || 0) + 18;
    const top = target.getBoundingClientRect().top + window.scrollY - offset;
    window.scrollTo({ top, behavior: "auto" });
  });
}

navToggle?.addEventListener("click", () => {
  const isOpen = nav.classList.toggle("is-open");
  header.classList.toggle("is-open", isOpen);
  navToggle.setAttribute("aria-expanded", String(isOpen));
});

nav?.addEventListener("click", (event) => {
  if (event.target.matches("a")) {
    nav.classList.remove("is-open");
    header.classList.remove("is-open");
    navToggle.setAttribute("aria-expanded", "false");
  }
});

if (gallery) {
  syncFilterCounts();

  filterButtons.forEach((button) => {
    button.addEventListener("click", () => setActiveFilter(button.dataset.filter));
  });

  gallery.addEventListener("click", (event) => {
    const button = event.target.closest(".gallery-item");
    if (!button) return;
    openLightbox(Number(button.dataset.index));
  });

  galleryLoadButton?.addEventListener("click", () => {
    visibleGalleryCount += galleryBatchSize;
    renderGallery(activeFilter);
  });
}

closeLightboxButton?.addEventListener("click", closeLightbox);
lightboxPrevButton?.addEventListener("click", () => moveLightbox(-1));
lightboxNextButton?.addEventListener("click", () => moveLightbox(1));

lightbox?.addEventListener("click", (event) => {
  if (event.target === lightbox) closeLightbox();
});

window.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && lightbox?.classList.contains("is-open")) {
    closeLightbox();
  }
  if (event.key === "ArrowLeft" && lightbox?.classList.contains("is-open")) {
    moveLightbox(-1);
  }
  if (event.key === "ArrowRight" && lightbox?.classList.contains("is-open")) {
    moveLightbox(1);
  }
});

leadForms.forEach((leadForm) => {
  const formStatus = leadForm.querySelector("[data-form-status]");
  const submitButton = leadForm.querySelector('button[type="submit"]');
  const submitText = submitButton?.textContent || "Send request";
  const setFormStatus = (message, state) => {
    if (!formStatus) return;
    formStatus.classList.remove("is-error", "is-success");
    if (state) formStatus.classList.add(state);
    formStatus.textContent = message;
  };

  leadForm.addEventListener("submit", async (event) => {
    event.preventDefault();

    if (!leadForm.checkValidity()) {
      leadForm.reportValidity();
      return;
    }

    setFormStatus("Sending your request...");

    if (submitButton) {
      submitButton.disabled = true;
      submitButton.textContent = "Sending...";
    }

    try {
      const response = await fetch(leadForm.action, {
        method: "POST",
        body: new FormData(leadForm),
        headers: {
          Accept: "application/json"
        }
      });
      const isJson = response.headers.get("content-type")?.includes("application/json");
      const result = isJson ? await response.json() : {};

      if (!response.ok || result.ok === false) {
        throw new Error(result.message || "We could not send the request. Please email rene@bjornsondesigns.com directly.");
      }

      leadForm.reset();
      setFormStatus(result.message || "Thank you. A member of the Bjornson team will follow up shortly.", "is-success");
    } catch (error) {
      setFormStatus(error.message || "We could not send the request. Please email rene@bjornsondesigns.com directly.", "is-error");
    } finally {
      if (submitButton) {
        submitButton.disabled = false;
        submitButton.textContent = submitText;
      }
    }
  });
});

window.addEventListener("scroll", syncHeader, { passive: true });
window.addEventListener("hashchange", settleInitialHash);

syncHeader();
renderGallery(activeFilter);
settleInitialHash();
enhancePointerEffects();
