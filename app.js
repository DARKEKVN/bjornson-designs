const labels = {
  kitchens: "Kitchen",
  bathrooms: "Bathroom",
  showroom: "Showroom"
};

const galleryItems = Object.entries(galleryFiles).flatMap(([category, files]) =>
  files.map((file, index) => ({
    category,
    file,
    title: makeTitle(file, category, index + 1)
  }))
);

